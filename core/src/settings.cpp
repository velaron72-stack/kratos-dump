struct B {
  SettingDef d;
  B& range(double lo, double hi) { d.min = lo; d.max = hi; return *this; }
  B& opts(std::vector<EnumOption> o) { d.options = std::move(o); return *this; }
  B& ui() { d.scope = "ui"; return *this; }
  B& adv() { d.advanced = true; return *this; }
};

B mk(const char* key, const char* cat, const char* title, SettingKind k, Json def, const char* purpose, const char* effect,
     const char* perf, const char* limits, const char* example) {
  B b;
  b.d.key = key;
  b.d.category = cat;
  b.d.title = title;
  b.d.kind = k;
  b.d.def = std::move(def);
  b.d.info = {purpose, effect, perf, limits, example};
  return b;
}

Json arr(std::initializer_list<const char*> v) {
  Json a = Json::array();
  for (auto s : v) a.push(Json(s));
  return a;
}

