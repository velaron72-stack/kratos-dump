const std::vector<SettingDef>& all_settings() { return settings_cache(); }

const SettingDef* find_setting(const std::string& key) {
  static const std::unordered_map<std::string, const SettingDef*> idx = [] {
    std::unordered_map<std::string, const SettingDef*> m;
    for (auto& d : settings_cache()) m[d.key] = &d;
    return m;
  }();
  auto it = idx.find(key);
  return it == idx.end() ? nullptr : it->second;
}

const std::vector<ProfileDef>& builtin_profiles() {
  static const std::vector<ProfileDef> p = build_profiles();
  return p;
}

const ProfileDef* find_profile(const std::string& id) {
  for (auto& p : builtin_profiles())
    if (p.id == id) return &p;
  return nullptr;
}

Json defaults_json() {
  Json o = Json::object();
  for (auto& d : all_settings()) o.set(d.key, d.def);
  return o;
}

Json profile_values(const std::string& profile_id) {
  Json o = defaults_json();
  if (const ProfileDef* p = find_profile(profile_id)) {
    for (auto& kv : p->overrides) {
      const SettingDef* d = find_setting(kv.first);
      Json nv;
      std::string msg;
      if (d && normalize(*d, kv.second, nv, msg)) o.set(kv.first, nv);
    }
  }
  return o;
}

Json schema_json() {
  Json root = Json::object();
  root.set("version", 1);
  Json cats = Json::array();
  for (auto& c : setting_categories()) {
    Json j = Json::object();
    j.set("id", c.id);
    j.set("title", c.title);
    j.set("description", c.description);
    cats.push(j);
  }
  root.set("categories", cats);
  Json sets = Json::array();
  static const char* kinds[] = {"bool", "int", "number", "enum", "string", "flags"};
  for (auto& d : all_settings()) {
    Json j = Json::object();
    j.set("key", d.key);
    j.set("category", d.category);
    j.set("title", d.title);
    j.set("kind", kinds[(int)d.kind]);
    j.set("default", d.def);
    if (d.kind == SettingKind::Int || d.kind == SettingKind::Number) {
      j.set("min", d.min);
      j.set("max", d.max);
    }
    if (!d.options.empty()) {
      Json oo = Json::array();
      for (auto& o : d.options) {
        Json x = Json::object();
        x.set("value", o.value);
        x.set("label", o.label);
        oo.push(x);
      }
      j.set("options", oo);
    }
    j.set("scope", d.scope);
    j.set("advanced", d.advanced);
    Json info = Json::object();
    info.set("purpose", d.info.purpose);
    info.set("effect", d.info.effect);
    info.set("performance", d.info.performance);
    info.set("limits", d.info.limits);
    info.set("example", d.info.example);
    j.set("info", info);
    sets.push(j);
  }
  root.set("settings", sets);
  Json profs = Json::array();
  for (auto& p : builtin_profiles()) {
    Json j = Json::object();
    j.set("id", p.id);
    j.set("title", p.title);
    j.set("description", p.description);
    j.set("values", profile_values(p.id));
    profs.push(j);
  }
  root.set("profiles", profs);
  return root;
}

// ---------------- Config ----------------
Config::Config() {
  for (auto& d : all_settings()) v_[d.key] = d.def;
}

Config::Config(const Config& o) : v_(o.v_) {}
Config& Config::operator=(const Config& o) {
  if (this != &o) {
    v_ = o.v_;
    std::lock_guard<std::mutex> g(mu_);
    touched_.clear();
  }
  return *this;
}

Config Config::from_json(const Json& obj, std::vector<ConfigIssue>* issues) {
  Config c;
  if (!obj.is_object()) {
    if (issues) issues->push_back({"", "конфигурация должна быть объектом JSON"});
    return c;
  }
  for (auto& kv : obj.members()) {
    const SettingDef* d = find_setting(kv.first);
    if (!d) {
      if (issues) issues->push_back({kv.first, "неизвестный параметр проигнорирован"});
      continue;
    }
    Json nv;
    std::string msg;
    if (normalize(*d, kv.second, nv, msg)) {
      c.v_[kv.first] = nv;
    } else {
      if (issues) issues->push_back({kv.first, msg});
      // Integers outside the range are clamped, everything else keeps the default.
      if (d->kind == SettingKind::Int && nv.is_int()) c.v_[kv.first] = nv;
    }
  }
  return c;
}

Json Config::to_json() const {
  Json o = Json::object();
  for (auto& d : all_settings()) o.set(d.key, v_.at(d.key));
  return o;
}

const Json& Config::get(const std::string& key) const {
  auto it = v_.find(key);
  if (it == v_.end()) throw std::logic_error("unknown setting: " + key);
  {
    std::lock_guard<std::mutex> g(mu_);
    touched_.insert(key);
  }
  return it->second;
}

bool Config::b(const std::string& key) const { return get(key).as_bool(); }
i64 Config::i(const std::string& key) const { return get(key).as_int(); }
double Config::n(const std::string& key) const { return get(key).as_double(); }
std::string Config::s(const std::string& key) const { return get(key).as_string(); }

std::vector<std::string> Config::list(const std::string& key) const {
  const Json& j = get(key);
  std::vector<std::string> out;
  if (j.is_array()) {
    for (auto& e : j.elems()) out.push_back(e.as_string());
  } else if (j.is_string()) {
    out = split(j.as_string(), ',');
  }
  return out;
}

bool Config::flag(const std::string& key, const std::string& value) const {
  for (auto& x : list(key))
    if (x == value) return true;
  return false;
}

u64 Config::limit(const std::string& key) const {
  i64 v = get(key).as_int();
  return v <= 0 ? 0 : (u64)v;
}

std::vector<std::string> Config::diff_from(const std::string& profile_id) const {
  Json pv = profile_values(profile_id);
  std::vector<std::string> out;
  for (auto& d : all_settings()) {
    const Json* p = pv.find(d.key);
    if (!p) continue;
    if (p->dump() != v_.at(d.key).dump()) out.push_back(d.key);
  }
  return out;
}

void Config::set(const std::string& key, const Json& v) {
  const SettingDef* d = find_setting(key);
  if (!d) throw std::logic_error("unknown setting: " + key);
  Json nv;
  std::string msg;
  if (normalize(*d, v, nv, msg)) v_[key] = nv;
  else if (d->kind == SettingKind::Int && nv.is_int()) v_[key] = nv;
}

std::set<std::string> Config::touched() const {
  std::lock_guard<std::mutex> g(mu_);
  return touched_;
}
void Config::clear_touched() const {
  std::lock_guard<std::mutex> g(mu_);
  touched_.clear();
}

