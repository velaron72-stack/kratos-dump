bool flag_has(const SettingDef& d, const std::string& v) {
  for (auto& o : d.options)
    if (o.value == v) return true;
  return false;
}

// Validates and normalizes a value for a setting. Returns false with msg if invalid.
bool normalize(const SettingDef& d, const Json& in, Json& out, std::string& msg) {
  switch (d.kind) {
    case SettingKind::Bool:
      if (in.is_bool()) { out = in; return true; }
      if (in.is_int() && (in.as_int() == 0 || in.as_int() == 1)) { out = Json(in.as_int() == 1); return true; }
      msg = "ожидается true или false";
      return false;
    case SettingKind::Int: {
      i64 x;
      if (in.is_number()) {
        x = in.as_int();
      } else {
        u64 pv;
        if (in.is_string() && parse_u64(in.as_string(), pv)) x = (i64)pv;
        else {
          msg = "ожидается целое число";
          return false;
        }
      }
      if (x < (i64)d.min || x > (i64)d.max) {
        msg = strf("значение %lld вне диапазона %lld..%lld", (long long)x, (long long)d.min, (long long)d.max);
        out = Json((long long)std::max<i64>((i64)d.min, std::min<i64>((i64)d.max, x)));
        return false;
      }
      out = Json((long long)x);
      return true;
    }
    case SettingKind::Number:
      if (!in.is_number()) { msg = "ожидается число"; return false; }
      out = Json(in.as_double());
      return true;
    case SettingKind::Enum:
      if (in.is_string() && flag_has(d, in.as_string())) { out = in; return true; }
      msg = "недопустимое значение";
      return false;
    case SettingKind::String:
      if (in.is_string()) { out = in; return true; }
      msg = "ожидается строка";
      return false;
    case SettingKind::Flags: {
      std::vector<std::string> items;
      if (in.is_array()) {
        for (auto& e : in.elems()) {
          if (!e.is_string()) { msg = "ожидается список строк"; return false; }
          items.push_back(e.as_string());
        }
      } else if (in.is_string()) {
        items = split(in.as_string(), ',');
      } else {
        msg = "ожидается список";
        return false;
      }
      Json a = Json::array();
      std::set<std::string> seen;
      for (auto& it : items) {
        if (!flag_has(d, it)) { msg = "неизвестный элемент: " + it; return false; }
        if (seen.insert(it).second) a.push(Json(it));
      }
      out = a;
      return true;
    }
  }
  return false;
}

